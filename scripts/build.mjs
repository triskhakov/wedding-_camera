import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const [html, apiSource, manifestSource] = await Promise.all([
    readFile(resolve(root, 'index.html'), 'utf8'),
    readFile(resolve(root, 'worker/api.mjs'), 'utf8'),
    readFile(resolve(root, '.openai/hosting.json'), 'utf8'),
]);

// Keep the artifact independent of build-time environment and local secrets.
// The API module is deliberately self-contained so no bundler is required.
if (/^\s*import\s|^\s*export\s+(?:default|\{|\*)/m.test(apiSource)) {
    throw new Error('worker/api.mjs must use named declarations and contain no imports or re-exports');
}
if (!/^\s*export\s+(?:async\s+)?function\s+handleApi\b/m.test(apiSource)) {
    throw new Error('worker/api.mjs must export function handleApi');
}
const manifest = JSON.parse(manifestSource);
const api = apiSource.replace(/^(\s*)export\s+(?=(?:async\s+)?function\b|const\b|let\b|class\b)/gm, '$1');
const source = `// Generated by scripts/build.mjs. Edit index.html or worker/api.mjs instead.
${api}

const weddingPage = ${JSON.stringify(html)};
const responseSecurityHeaders = {
    'cache-control': 'no-store',
    'x-content-type-options': 'nosniff',
    'referrer-policy': 'no-referrer',
};

export default {
    async fetch(request, env, ctx) {
        let response;
        try {
            const pathname = new URL(request.url).pathname;
            if ((pathname === '/' || pathname === '/index.html') &&
                (request.method === 'GET' || request.method === 'HEAD')) {
                response = new Response(request.method === 'HEAD' ? null : weddingPage, {
                    headers: { 'content-type': 'text/html; charset=utf-8' },
                });
            } else {
                response = await handleApi(request, env, ctx);
            }
        } catch {
            response = new Response(JSON.stringify({ ok: false, code: 'INTERNAL_ERROR', message: 'Сервис временно недоступен.' }), {
                status: 500,
                headers: { 'content-type': 'application/json; charset=utf-8' },
            });
        }
        const headers = new Headers(response.headers);
        for (const [name, value] of Object.entries(responseSecurityHeaders)) headers.set(name, value);
        return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
    },
};
`;

await Promise.all([
    mkdir(resolve(root, 'worker'), { recursive: true }),
    mkdir(resolve(root, 'dist/server'), { recursive: true }),
    mkdir(resolve(root, 'dist/.openai'), { recursive: true }),
]);
await Promise.all([
    writeFile(resolve(root, 'worker/index.js'), source),
    writeFile(resolve(root, 'dist/server/index.js'), source),
    writeFile(resolve(root, 'dist/.openai/hosting.json'), JSON.stringify(manifest, null, 2) + '\n'),
]);
console.log('Built Worker ESM artifact in dist/');
